def build_prompt(label_path: str) -> str:
    """根据标签路径生成完整的用户提示词"""
    desc = LABEL_DESCRIPTIONS.get(label_path, "（该标签暂无特定定义，请根据标签名称自行判断）")
    rules = EXCLUSION_RULES.get(label_path, "无特殊排他规则，请根据标签定义判断图片是否匹配。")
    return COMMON_PROMPT_TEMPLATE.format(
        label_path=label_path,
        label_description=desc,
        exclusion_rules=rules,
    )


